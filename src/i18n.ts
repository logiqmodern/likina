export const messages: Record<Lang, Messages> = { bg, en };

/** Text from the database in the page language, falling back to BG (with lang="bg" on the element, §7). */
export function pick(lang: Lang, bgText: string | null, enText: string | null): { text: string | null; lang: Lang } {
  if (lang === "en" && enText) return { text: enText, lang: "en" };
  return { text: bgText ?? enText, lang: bgText ? "bg" : "en" };
}

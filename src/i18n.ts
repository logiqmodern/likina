export const href = {
  page: (lang: Lang, page: StaticPage) => STATIC[page][lang],
  category: (lang: Lang, bgSlug: string) => {
    const c = CATEGORY_SLUGS.find((x) => x.bg === bgSlug);
    return lang === "bg" ? `/${bgSlug}` : `/en/${c?.en ?? bgSlug}`;
  },
  artwork: (lang: Lang, slug: string) => (lang === "bg" ? `/tvorba/${slug}` : `/en/artwork/${slug}`),
  artist: (lang: Lang, slug: string) => (lang === "bg" ? `/avtori/${slug}` : `/en/artists/${slug}`),
  order: (lang: Lang, token: string) => (lang === "bg" ? `/porachka/${token}` : `/en/order/${token}`),
};

